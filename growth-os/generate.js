// Generates, from growth-os/definitions.js and the Worker's own builders:
//   migrations/0012_growth_os_seed.sql       metric definitions + registries
//   test/fixtures/growth-os/envelope/*.json  one envelope per state (+ combinations)
//   test/fixtures/growth-os/week/*.json      /growth/week responses
//   test/fixtures/growth-os/entity/*.json    /growth/entity responses
//
// Usage: node growth-os/generate.js          write the files
//        node growth-os/generate.js --check  exit 1 if any checked-in file differs
//
// Fixture values are synthetic and dated in the year 2000 so no one mistakes them
// for measurements.

"use strict";

const fs = require("fs");
const path = require("path");
const { loadWorker, root } = require("./load-worker");
const spec = require("./definitions");

const FIXTURE_NOW = "2000-01-09T06:00:00.000Z";

function sqlLiteral(value) {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "number") return String(value);
  return `'${String(value).replace(/'/g, "''")}'`;
}

// D1 caps one SQL statement at 100 KB. Chunk so the seed never approaches it as
// definitions grow.
const INSERT_CHUNK_ROWS = 50;

function insert(table, columns, rows) {
  let out = "";
  for (let i = 0; i < rows.length; i += INSERT_CHUNK_ROWS) {
    const lines = rows.slice(i, i + INSERT_CHUNK_ROWS).map((row) => `  (${columns.map((c) => sqlLiteral(row[c])).join(", ")})`);
    out += `INSERT INTO ${table} (${columns.join(", ")}) VALUES\n${lines.join(",\n")};\n`;
  }
  return out;
}

const DEFINITION_COLUMNS = [
  "metric_key", "version", "label", "surface", "unit", "confidence", "formula", "session_basis", "basis_label",
  "grains", "direction", "comparison_mode", "treatment", "source_tables", "effective_from", "effective_to",
  "change_note", "created_at"
];

// A definition as D1 returns it: JSON columns are strings.
function definitionRow(d) {
  const row = {};
  for (const c of DEFINITION_COLUMNS) row[c] = d[c] === undefined ? null : d[c];
  row.grains = JSON.stringify(d.grains);
  row.source_tables = JSON.stringify(d.source_tables);
  return row;
}

// Every row carries the migration that introduced it. A migration already applied
// in production must never change (test: growth-os/applied-migrations.json), so
// additions get a new tag and land in a new file.
function seedMigrations() {
  const tag = (row) => row.migration || spec.SEED_MIGRATION;
  const tags = new Set([...spec.definitions, ...spec.breakdowns, ...spec.reasons, ...spec.locations].map(tag));
  const files = {};
  for (const t of [...tags].sort()) {
    const isSeed = t === spec.SEED_MIGRATION;
    const name = isSeed ? `${t}_growth_os_seed.sql` : `${t}_growth_os_additions.sql`;
    const defs = spec.definitions.filter((d) => tag(d) === t);
    const breakdowns = spec.breakdowns.filter((b) => tag(b) === t);
    const reasons = spec.reasons.filter((r) => tag(r) === t);
    const locations = spec.locations.filter((l) => tag(l) === t);
    let sql = "-- GENERATED by `node growth-os/generate.js` from growth-os/definitions.js. Do not edit.\n";
    sql += isSeed ? "-- Growth OS metric definitions and structural registries (L0 seed).\n\n" : "-- Growth OS additions.\n\n";
    // A redefinition closes the version it replaces, so exactly one stays open.
    for (const d of defs.filter((x) => x.version > 1)) {
      sql += `UPDATE metric_definitions SET effective_to = ${sqlLiteral(d.effective_from)} WHERE metric_key = ${sqlLiteral(d.metric_key)} AND version = ${d.version - 1};\n`;
    }
    const parts = [];
    if (defs.length) parts.push(insert("metric_definitions", DEFINITION_COLUMNS, defs.map(definitionRow)));
    if (breakdowns.length) parts.push(insert("dim_breakdown", ["breakdown_id", "source", "dims", "label", "purpose", "sort_order"],
      breakdowns.map((b) => ({ ...b, dims: JSON.stringify(b.dims) }))));
    if (reasons.length) parts.push(insert("dim_reason", ["reason_code", "label", "applies_to", "owner", "sort_order"],
      reasons.map((r) => ({ ...r, applies_to: JSON.stringify(r.applies_to) }))));
    if (locations.length) parts.push(insert("dim_location", ["location_id", "name", "kind", "channel", "partner_name", "notes"], locations));
    sql += parts.join("\n");
    files[path.join("migrations", name)] = sql;
  }
  return files;
}

// A version is closed by the next version's effective_from — the same UPDATE the
// generated migration runs — so fixtures see exactly what D1 holds.
function effectiveTo(d) {
  const next = spec.definitions.find((x) => x.metric_key === d.metric_key && x.version === d.version + 1);
  return next ? next.effective_from : d.effective_to;
}

function definitionRowsInEffect(asOf) {
  return spec.definitions
    .map((d) => ({ ...d, effective_to: effectiveTo(d) }))
    .filter((d) => d.effective_from <= asOf && (d.effective_to === null || d.effective_to > asOf))
    .map(definitionRow);
}

