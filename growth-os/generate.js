// The Sunday week whose first day is at least `minDay` days after the drop.
function floorWeek(worker, dropDate, minDay) {
  let start = worker.addDays(dropDate, minDay);
  while (!worker.isSunday(start)) start = worker.addDays(start, 1);
  return { week_start: start, week_end: worker.addDays(start, 6), as_of: worker.addDays(start, 6), is_complete: true, timezone: "Africa/Cairo" };
}

