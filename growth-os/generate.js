function buildGeneratedFiles() {
  const worker = loadWorker();
  return { ...seedMigrations(), ...fixtures(worker) };
}

function main() {
  const check = process.argv.includes("--check");
  const files = buildGeneratedFiles();
  let differ = 0;
  for (const [rel, content] of Object.entries(files)) {
    const abs = path.join(root, rel);
    const current = fs.existsSync(abs) ? fs.readFileSync(abs, "utf8").replace(/\r\n/g, "\n") : null;
    if (current === content) continue;
    differ += 1;
    if (check) {
      console.error(`differs: ${rel}`);
    } else {
      fs.mkdirSync(path.dirname(abs), { recursive: true });
      fs.writeFileSync(abs, content, "utf8");
      console.log(`wrote ${rel}`);
    }
  }
  if (check && differ) process.exitCode = 1;
  if (!differ) console.log(`${Object.keys(files).length} generated files up to date.`);
}

if (require.main === module) main();

